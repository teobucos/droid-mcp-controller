// Generates docs/TOOLS.md from the schemas and descriptions the server actually
// registers (listed over an in-memory MCP connection), so the reference cannot drift.
//   node scripts/gen-tool-reference.mjs          write docs/TOOLS.md
//   node scripts/gen-tool-reference.mjs --check  fail if docs/TOOLS.md is stale
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { Client } from '@modelcontextprotocol/sdk/client/index.js';
import { InMemoryTransport } from '@modelcontextprotocol/sdk/inMemory.js';
import { createMcp } from '../src/mcp.mjs';

const target = fileURLToPath(new URL('../docs/TOOLS.md', import.meta.url));
const server = createMcp(new Proxy({}, { get: () => () => { throw new Error('reference generation never calls tools'); } }), {});
const [clientSide, serverSide] = InMemoryTransport.createLinkedPair();
const client = new Client({ name: 'tool-reference', version: '1' });
await Promise.all([server.connect(serverSide), client.connect(clientSide)]);
const tools = (await client.listTools()).tools;
await client.close();

function fields(schema, indent = '') {
  const required = new Set(schema.required ?? []);
  return Object.entries(schema.properties ?? {}).map(([name, property]) => {
    const type = property.type ?? (property.anyOf ? property.anyOf.map((p) => p.type ?? 'value').join(' | ') : 'value');
    const bits = [`${indent}- \`${name}\`${required.has(name) ? ' (required)' : ''}: ${type}`];
    if (property.enum) bits.push(`one of ${property.enum.map((v) => `\`${v}\``).join(', ')}`);
    if (property.minimum !== undefined || property.maximum !== undefined) bits.push(`${property.minimum ?? ''}..${property.maximum ?? ''}`);
    if (property.default !== undefined) bits.push(`default ${JSON.stringify(property.default)}`);
    if (property.description) bits.push(property.description);
    return bits.join('; ');
  }).join('\n');
}

const section = (tool) => [
  `### \`${tool.name}\``, '', tool.description, '',
  '**Input**', '', fields(tool.inputSchema) || '_none_', '',
  ...(tool.outputSchema ? ['**Output**: JSON object with ' + Object.keys(tool.outputSchema.properties ?? {}).map((key) => `\`${key}\``).join(', '), ''] : []),
].join('\n');
const text = [
  '# Tool reference', '',
  '<!-- Generated by scripts/gen-tool-reference.mjs from the registered schemas. Do not edit by hand. -->', '',
  'Errors use MCP `isError` with `{"error": {code, message, retryable, action}}`. Successful results carry the same JSON as `structuredContent` and text.', '',
  '## Session tools', '', tools.map(section).join('\n'),
].join('\n');

if (process.argv.includes('--check')) {
  if (!existsSync(target) || readFileSync(target, 'utf8') !== text) { console.error('docs/TOOLS.md is stale: run node scripts/gen-tool-reference.mjs'); process.exit(1); }
} else { mkdirSync(fileURLToPath(new URL('../docs', import.meta.url)), { recursive: true }); writeFileSync(target, text); }
